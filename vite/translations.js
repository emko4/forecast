import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';

/**
 * Translations live beside what they translate: every folder may have a
 * `locales/<language>.yml`. Before a build (and when one of them changes
 * while developing) they are gathered into one file per language, each key
 * prefixed with the folders it came from — src/scenes/Error/locales/en.yml
 * gives "scenes.Error.<key>". The application imports the gathered files
 * (src/services/translations); they are generated, not kept in git. So is
 * the list of react-intl's own data (plurals, date formats) for the same
 * languages: the old build found those files by name while bundling.
 */
export default function translations({ root = 'src', localeDir = 'locales', languages, output, jsonSpacing = 4 }) {
    const localeFiles = (language) => {
        const found = [];
        const walk = (dir) => {
            fs.readdirSync(dir, { withFileTypes: true })
                .sort((a, b) => (a.name < b.name ? -1 : 1))
                .forEach((entry) => {
                    const file = path.posix.join(dir, entry.name);

                    if (entry.isDirectory()) walk(file);
                    else if (path.posix.basename(dir) === localeDir && entry.name === `${language}.yml`) found.push(file);
                });
        };

        walk(root);

        return found;
    };

    const generate = () => {
        fs.mkdirSync(output, { recursive: true });

        languages.forEach((language) => {
            const messages = {};

            localeFiles(language).forEach((file) => {
                // the folders between the root and the locales folder
                const keys = path.posix.dirname(file).split('/').slice(1, -1);
                let content;

                try {
                    content = yaml.load(fs.readFileSync(file, 'utf8'));
                } catch (error) {
                    throw new Error(`Wrong YAML format ${file} - ${error}`);
                }

                Object.keys(content || {}).forEach((key) => {
                    messages[`${keys.join('.')}.${key}`] = content[key];
                });
            });

            const stringifyData = JSON.stringify(messages, null, jsonSpacing);
            const comment = '/* eslint-disable */\n// Generated by the translations plugin - DO NOT EDIT!!!\n\n';

            // the file the application imports, and a json one for human translations
            fs.writeFileSync(`${output}/${language}.js`, `${comment}export default ${stringifyData};`);
            fs.writeFileSync(`${output}/${language}.json`, stringifyData);
        });

        const imports = languages.map((language) => `import ${language} from './${language}';\n`).join('');
        const exports = `export default {\n${languages.map((language) => `${' '.repeat(jsonSpacing)}${language},\n`).join('')}};`;

        fs.writeFileSync(`${output}/index.js`, `// Generated by the translations plugin - DO NOT EDIT!!!\n\n${imports}\n${exports}\n`);

        const dataImports = languages.map((language) => `import ${language} from 'react-intl/locale-data/${language}';\n`).join('');

        fs.writeFileSync(`${output}/localeData.js`, `// Generated by the translations plugin - DO NOT EDIT!!!\n\n${dataImports}\n${exports}\n`);
    };

    return {
        name: 'translations',
        buildStart() {
            generate();
        },
        configureServer(server) {
            server.watcher.on('all', (event, file) => {
                if (file.endsWith('.yml') && path.basename(path.dirname(file)) === localeDir) generate();
            });
        },
    };
}
